CREATE TABLE bus_company (
  company_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  company_name VARCHAR2(100) NOT NULL,
  license_number VARCHAR2(50) UNIQUE,
  phone VARCHAR2(25),
  address VARCHAR2(200),
  ceo_name VARCHAR2(100),
  status VARCHAR2(20) DEFAULT 'ACTIVE' CHECK (status IN ('ACTIVE','INACTIVE'))
);

CREATE TABLE bus (
  bus_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  company_id NUMBER NOT NULL REFERENCES bus_company(company_id),
  plate_number VARCHAR2(30) UNIQUE NOT NULL,
  capacity NUMBER(3) NOT NULL CHECK (capacity > 0),
  bus_type VARCHAR2(40),
  status VARCHAR2(20) DEFAULT 'ACTIVE' CHECK (status IN ('ACTIVE','INACTIVE','MAINTENANCE'))
);

CREATE TABLE passenger (
  passenger_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  full_name VARCHAR2(120) NOT NULL,
  phone VARCHAR2(25) UNIQUE,
  email VARCHAR2(120)
);

CREATE TABLE trip (
  trip_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  bus_id NUMBER NOT NULL REFERENCES bus(bus_id),
  origin VARCHAR2(100) NOT NULL,
  destination VARCHAR2(100) NOT NULL,
  departure_time TIMESTAMP NOT NULL,
  arrival_time TIMESTAMP,
  fare NUMBER(10,2) NOT NULL CHECK (fare >= 0),
  status VARCHAR2(20) DEFAULT 'SCHEDULED'
);

CREATE TABLE reservation (
  reservation_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  passenger_id NUMBER NOT NULL REFERENCES passenger(passenger_id),
  trip_id NUMBER NOT NULL REFERENCES trip(trip_id),
  reservation_date TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
  status VARCHAR2(20) DEFAULT 'BOOKED' CHECK (status IN ('BOOKED','CANCELLED','COMPLETED'))
);

CREATE TABLE payment (
  payment_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  reservation_id NUMBER NOT NULL REFERENCES reservation(reservation_id),
  amount NUMBER(10,2) NOT NULL CHECK (amount >= 0),
  payment_method VARCHAR2(30),
  payment_date TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
  status VARCHAR2(20) DEFAULT 'PENDING'
);

CREATE TABLE ticket (
  ticket_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  reservation_id NUMBER NOT NULL REFERENCES reservation(reservation_id),
  ticket_code VARCHAR2(50) UNIQUE NOT NULL,
  issued_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
  status VARCHAR2(20) DEFAULT 'VALID'
);

